bool pinyin_initials(const char* utf8, char* out, size_t out_size) {
    if (!utf8 || !out || out_size == 0)
        return false;
    size_t o = 0;
    for (const unsigned char* p = (const unsigned char*)utf8; *p; p++) {
        // UTF-8 CJK basic plane: E4..E9 lead byte
        if (p[0] >= 0xE4 && p[0] <= 0xE9 && (p[1] & 0xC0) == 0x80 && (p[2] & 0xC0) == 0x80) {
            unsigned int cp = ((unsigned int)(p[0] & 0x0F) << 12) | ((unsigned int)(p[1] & 0x3F) << 6) | (p[2] & 0x3F);
            p += 2;
            if (cp < PINYIN_START || cp >= PINYIN_START + PINYIN_COUNT)
                continue;
            char c = PINYIN_DATA[cp - PINYIN_START];
            if (c == '.' || o + 1 >= out_size)
                continue;
            out[o++] = c;
            continue;
        }
        // ASCII: letters lowercased, digits kept, everything else dropped
        if (*p >= 'A' && *p <= 'Z') {
            if (o + 1 < out_size)
                out[o++] = *p - 'A' + 'a';
        } else if ((*p >= 'a' && *p <= 'z') || (*p >= '0' && *p <= '9')) {
            if (o + 1 < out_size)
                out[o++] = *p;
        }
    }
    out[o] = '\0';
    return o > 0;
}
